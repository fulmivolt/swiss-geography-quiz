let language = "de";
try {
  const saved = globalThis.localStorage?.getItem("swiss-quiz-language");
  language = ["de", "en"].includes(saved) ? saved : globalThis.navigator?.language?.startsWith("de") ? "de" : "en";
} catch { /* Storage can be unavailable in restricted browser previews. */ }

export const getLanguage = () => language;
export function setLanguage(value) {
  if (!["de", "en"].includes(value)) return;
  language = value;
  try { globalThis.localStorage?.setItem("swiss-quiz-language", value); } catch { /* Preference remains active in memory. */ }
}
export function t(key, values = {}) {
  const template = messages[language][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

// Keep references only to original static text; quiz content is translated when rendered.
const staticText = [];
const staticAttributes = [];
export function initializeStaticTranslations(root = document) {
  const walker = document.createTreeWalker(root.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const key = node.textContent.trim();
    if (messages.en[key]) staticText.push({ node, key, prefix: node.textContent.match(/^\s*/)[0], suffix: node.textContent.match(/\s*$/)[0] });
  }
  root.querySelectorAll("[aria-label], [placeholder], [title]").forEach((element) => {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      const key = element.getAttribute(attribute);
      if (messages.en[key]) staticAttributes.push({ element, attribute, key });
    }
  });
  translateStatic();
}
export function translateStatic() {
  document.documentElement.lang = language;
  document.title = language === "de" ? "Schweiz — Geografie-Quiz" : "Switzerland — Geography Quiz";
  for (const { node, key, prefix, suffix } of staticText) if (node.isConnected) node.textContent = prefix + t(key) + suffix;
  for (const { element, attribute, key } of staticAttributes) element.setAttribute(attribute, t(key));
}
